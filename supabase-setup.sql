create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  description text not null default '',
  icon text not null default '🛍️',
  price numeric(10,2) null check (price is null or price >= 0),
  stock integer null check (stock is null or stock >= 0),
  image_url text null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.admins enable row level security;
alter table public.products enable row level security;
revoke all on public.admins from anon, authenticated;
grant select on public.admins to authenticated;
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

create policy "Admin can read own admin record" on public.admins
for select to authenticated using (user_id = (select auth.uid()));

create policy "Public can read active products" on public.products
for select to anon, authenticated
using (active = true or exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

create policy "Admins can insert products" on public.products
for insert to authenticated
with check (exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

create policy "Admins can update products" on public.products
for update to authenticated
using (exists (select 1 from public.admins a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

create policy "Admins can delete products" on public.products
for delete to authenticated
using (exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

-- Bucket público para as imagens dos produtos. As imagens são públicas para exibição,
-- mas somente administradores autorizados podem enviar, alterar ou apagar arquivos.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-images', 'product-images', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/jpeg','image/png','image/webp'];

create policy "Anyone can view Copytec product photos" on storage.objects
for select to public using (bucket_id = 'product-images');

create policy "Copytec admins upload product photos" on storage.objects
for insert to authenticated
with check (bucket_id = 'product-images' and exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

create policy "Copytec admins update product photos" on storage.objects
for update to authenticated
using (bucket_id = 'product-images' and exists (select 1 from public.admins a where a.user_id = (select auth.uid())))
with check (bucket_id = 'product-images' and exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

create policy "Copytec admins delete product photos" on storage.objects
for delete to authenticated
using (bucket_id = 'product-images' and exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

